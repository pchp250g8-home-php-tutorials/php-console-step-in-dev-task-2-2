<?php
    // Вывод подсказки на экран
    print("Введите данные радарной станции (0 - конец ввода).\r\n");
    // Считываем первые два элемента
    $prev = intval(fgets(STDIN));  // ввод первой высоты
    $curr = intval(fgets(STDIN));  // ввод второй высоты
    $peaks_count = 0;  // счётчик пиков
    $b_done = false;  // флаг окончания цикла
    while (!$b_done)
    {
        $next_val = intval(fgets(STDIN));  // ввод третьей высоты
        // Если встретили 0, ввод окончен
        $b_done = ($next_val == 0);  // условие окончания цикла
        // Проверяем условие пика для текущего элемента
        if (!$b_done && ($curr > $prev) && ($curr > $next_val))
        {
            $peaks_count += 1;  // счётчик пиков увеличили на 1
        }   
        // Сдвигаем «окно» из трёх элементов вперед
        $prev = $curr;
        $curr = $next_val;
    }
    print("Количество пиков: " . $peaks_count . "\r\n");  // вывод на экран
?>